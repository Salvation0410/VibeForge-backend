-- 停写排空并备份后新增；观察期限不授予接管或重算资格。
CREATE TABLE IF NOT EXISTS customer_service_knowledge_prepare_execution (
 taskId BIGINT NOT NULL PRIMARY KEY,
 operationId VARCHAR(128) COLLATE utf8mb4_bin NOT NULL,
 fence BIGINT NOT NULL,
 executorId VARCHAR(32) COLLATE utf8mb4_bin NOT NULL,
 status VARCHAR(16) NOT NULL COMMENT 'STARTED/UNKNOWN/COMPLETE',
 observationDeadline DATETIME NOT NULL,
 receiptJson MEDIUMTEXT NULL,
 createTime DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updateTime DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
